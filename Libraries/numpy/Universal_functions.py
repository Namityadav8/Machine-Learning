import numpy as np

arr1 = np.array([2,3,4,9,10,16])

print(np.sqrt(arr1))  #Square root of the array performed on each element in the array
print(np.exp(arr1))   #Exponential of the array performed on each element in the array
print(np.log(arr1))   #logarithm function on the array
print(np.sin(arr1))   #sine function on the array